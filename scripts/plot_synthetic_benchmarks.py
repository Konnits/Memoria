def resolve_observations_file(path: Path) -> Path:
    """Resolve a direct file path or a generated dataset directory."""
    path = path.expanduser().resolve()

    if path.is_file():
        if path.suffix.lower() not in {".parquet", ".csv"}:
            raise ValueError(
                f"Unsupported input file: {path}. Expected .parquet or .csv."
            )
        return path

    if not path.exists():
        raise FileNotFoundError(f"Input path does not exist: {path}")

    candidates = (
        path / "observations.parquet",
        path / "observations.csv",
    )
    for candidate in candidates:
        if candidate.exists():
            return candidate

    recursive_candidates = sorted(
        list(path.glob("**/observations.parquet"))
        + list(path.glob("**/observations.csv"))
    )

    if not recursive_candidates:
        raise FileNotFoundError(
            f"No observations.parquet or observations.csv found under {path}."
        )

    if len(recursive_candidates) > 1:
        formatted = "\n".join(f"  - {item}" for item in recursive_candidates[:20])
        raise ValueError(
            "The supplied directory contains multiple datasets. Point --input "
            "to one dataset directory or directly to one observations file.\n"
            f"Candidates:\n{formatted}"
        )

    return recursive_candidates[0]


def parse_channel_tokens(raw: str | None) -> list[str] | None:
    if raw is None:
        return None

    tokens = [item.strip() for item in raw.split(",") if item.strip()]
    if not tokens:
        return None
    return tokens


def _available_parquet_columns(file_path: Path) -> set[str]:
    import pyarrow.parquet as pq

    schema = pq.read_schema(file_path)
    return set(schema.names)


def _build_arrow_filter(
    available_columns: set[str],
    split: str,
    start_time: float | None,
    end_time: float | None,
):
    import pyarrow.dataset as ds

    expression = None

    def add(condition):
        nonlocal expression
        expression = condition if expression is None else expression & condition

    if split != "all" and "split" in available_columns:
        add(ds.field("split") == split)
    if start_time is not None and "time" in available_columns:
        add(ds.field("time") >= start_time)
    if end_time is not None and "time" in available_columns:
        add(ds.field("time") <= end_time)

    return expression


def read_parquet(
    file_path: Path,
    split: str,
    start_time: float | None,
    end_time: float | None,
) -> pd.DataFrame:
    """Read Parquet with column projection and predicate pushdown."""
    import pyarrow.dataset as ds

    available = _available_parquet_columns(file_path)
    columns = [name for name in DEFAULT_COLUMNS if name in available]

    if "time" not in columns or "value" not in columns:
        raise ValueError(
            f"{file_path} must contain at least the columns 'time' and 'value'."
        )

    dataset = ds.dataset(file_path, format="parquet")
    arrow_filter = _build_arrow_filter(
        available_columns=available,
        split=split,
        start_time=start_time,
        end_time=end_time,
    )
    table = dataset.to_table(columns=columns, filter=arrow_filter)
    return table.to_pandas()


def read_csv(
    file_path: Path,
    split: str,
    start_time: float | None,
    end_time: float | None,
) -> pd.DataFrame:
    """Read CSV in chunks to avoid unnecessary peak memory usage."""
    header = pd.read_csv(file_path, nrows=0)
    available = set(header.columns)
    columns = [name for name in DEFAULT_COLUMNS if name in available]

    if "time" not in columns or "value" not in columns:
        raise ValueError(
            f"{file_path} must contain at least the columns 'time' and 'value'."
        )

    chunks: list[pd.DataFrame] = []
    for chunk in pd.read_csv(
        file_path,
        usecols=columns,
        chunksize=1_000_000,
        low_memory=False,
    ):
        if split != "all" and "split" in chunk:
            chunk = chunk.loc[chunk["split"].astype(str) == split]
        if start_time is not None:
            chunk = chunk.loc[chunk["time"] >= start_time]
        if end_time is not None:
            chunk = chunk.loc[chunk["time"] <= end_time]

        if not chunk.empty:
            chunks.append(chunk)

    if not chunks:
        return pd.DataFrame(columns=columns)

    return pd.concat(chunks, ignore_index=True)


def read_observations(
    file_path: Path,
    split: str,
    start_time: float | None,
    end_time: float | None,
) -> pd.DataFrame:
    suffix = file_path.suffix.lower()
    if suffix == ".parquet":
        return read_parquet(file_path, split, start_time, end_time)
    if suffix == ".csv":
        return read_csv(file_path, split, start_time, end_time)
    raise ValueError(f"Unsupported input format: {suffix}")


def normalize_channel_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Guarantee a channel column for both univariate and multivariate data."""
    result = df.copy()

    if "channel" not in result.columns:
        result["channel"] = "target"
    else:
        result["channel"] = result["channel"].astype(str)

    if "channel_index" not in result.columns:
        mapping = {
            channel: index
            for index, channel in enumerate(pd.unique(result["channel"]))
        }
        result["channel_index"] = result["channel"].map(mapping).astype(np.int32)

    return result


def select_channels(
    df: pd.DataFrame,
    tokens: Sequence[str] | None,
) -> pd.DataFrame:
    if not tokens:
        return df

    requested_names: set[str] = set()
    requested_indices: set[int] = set()

    for token in tokens:
        try:
            requested_indices.add(int(token))
        except ValueError:
            requested_names.add(token)

    mask = df["channel"].isin(requested_names)
    if requested_indices:
        mask = mask | df["channel_index"].isin(requested_indices)

    selected = df.loc[mask].copy()
    if selected.empty:
        available = (
            df[["channel", "channel_index"]]
            .drop_duplicates()
            .sort_values("channel_index")
        )
        raise ValueError(
            "None of the requested channels were found.\n"
            f"Available channels:\n{available.to_string(index=False)}"
        )

    return selected


def temporal_downsample_group(group: pd.DataFrame, target_size: int) -> pd.DataFrame:
    """Uniformly preserve points over the complete temporal range."""
    if target_size <= 0:
        return group.iloc[0:0].copy()

    ordered = group.sort_values("time", kind="mergesort")
    if len(ordered) <= target_size:
        return ordered

    indices = np.linspace(
        0,
        len(ordered) - 1,
        num=target_size,
        dtype=np.int64,
    )
    indices = np.unique(indices)
    return ordered.iloc[indices]


def downsample_by_channel(df: pd.DataFrame, max_points: int) -> pd.DataFrame:
    if max_points <= 0:
        raise ValueError("--max-points must be greater than zero.")

    if len(df) <= max_points:
        return df.sort_values(["channel_index", "time"], kind="mergesort")

    counts = df.groupby("channel", observed=True, sort=False).size()
    channels = list(counts.index)
    total = int(counts.sum())

    allocations: dict[str, int] = {}
    assigned = 0

    for channel in channels:
        proportion = int(round(max_points * int(counts[channel]) / total))
        allocations[channel] = max(2, proportion)
        assigned += allocations[channel]

    while assigned > max_points:
        reducible = [
            channel for channel in channels if allocations[channel] > 2
        ]
        if not reducible:
            break
        channel = max(reducible, key=lambda item: allocations[item])
        allocations[channel] -= 1
        assigned -= 1

    while assigned < max_points:
        channel = max(
            channels,
            key=lambda item: int(counts[item]) - allocations[item],
        )
        if allocations[channel] >= int(counts[channel]):
            break
        allocations[channel] += 1
        assigned += 1

    sampled = [
        temporal_downsample_group(
            df.loc[df["channel"] == channel],
            min(allocations[channel], int(counts[channel])),
        )
        for channel in channels
    ]

    return pd.concat(sampled, ignore_index=True).sort_values(
        ["channel_index", "time"],
        kind="mergesort",
    )


def choose_interval_column(df: pd.DataFrame) -> str:
    for candidate in ("delta_t_channel", "delta_t", "delta_t_global"):
        if candidate in df.columns:
            return candidate
    raise ValueError(
        "The dataset has no delta-time column. Expected one of: "
        "delta_t_channel, delta_t, delta_t_global."
    )


def infer_title(file_path: Path, plot_type: str) -> str:
    dataset_name = file_path.parent.name
    label = "Serie irregular" if plot_type == "series" else "Intervalos irregulares"
    return f"{label}: {dataset_name}"


def plot_series_matplotlib(
    df: pd.DataFrame,
    title: str,
    style: str,
    show_clean: bool,
    overlay: bool,
):
    import matplotlib.pyplot as plt

    channels = (
        df[["channel", "channel_index"]]
        .drop_duplicates()
        .sort_values("channel_index")
    )
    channel_names = channels["channel"].tolist()
    n_channels = len(channel_names)

    if overlay or n_channels == 1:
        figure, axis = plt.subplots(figsize=(14, 6))
        axes = [axis] * n_channels
    else:
        figure, axes_array = plt.subplots(
            n_channels,
            1,
            figsize=(14, max(3.0 * n_channels, 5.0)),
            sharex=True,
            squeeze=False,
        )
        axes = [axis for axis in axes_array[:, 0]]

    for index, channel in enumerate(channel_names):
        axis = axes[index]
        channel_df = df.loc[df["channel"] == channel].sort_values("time")

        if style in {"line", "line-points"}:
            axis.plot(
                channel_df["time"],
                channel_df["value"],
                linewidth=0.8,
                label=f"{channel} observado",
            )
        if style in {"points", "line-points"}:
            axis.scatter(
                channel_df["time"],
                channel_df["value"],
                s=5,
                alpha=0.65,
                label=f"{channel} observado",
            )

        if show_clean and "clean_value" in channel_df.columns:
            axis.plot(
                channel_df["time"],
                channel_df["clean_value"],
                linewidth=1.0,
                alpha=0.85,
                label=f"{channel} limpio",
            )

        axis.set_ylabel("Valor")
        axis.grid(True, alpha=0.25)

        if not overlay:
            axis.set_title(str(channel))
            axis.legend(loc="best")
        elif index == n_channels - 1:
            axis.legend(loc="best", ncol=min(3, n_channels))

    axes[-1].set_xlabel("Tiempo")
    figure.suptitle(title)
    figure.tight_layout()
    return figure


def plot_intervals_matplotlib(
    df: pd.DataFrame,
    title: str,
    overlay: bool,
):
    import matplotlib.pyplot as plt

    interval_column = choose_interval_column(df)
    channels = (
        df[["channel", "channel_index"]]
        .drop_duplicates()
        .sort_values("channel_index")
    )
    channel_names = channels["channel"].tolist()
    n_channels = len(channel_names)

    if overlay or n_channels == 1:
        figure, axis = plt.subplots(figsize=(12, 6))
        axes = [axis] * n_channels
    else:
        figure, axes_array = plt.subplots(
            n_channels,
            1,
            figsize=(12, max(3.0 * n_channels, 5.0)),
            squeeze=False,
        )
        axes = [axis for axis in axes_array[:, 0]]

    for index, channel in enumerate(channel_names):
        axis = axes[index]
        values = (
            df.loc[df["channel"] == channel, interval_column]
            .replace([np.inf, -np.inf], np.nan)
            .dropna()
        )
        values = values.loc[values >= 0]

        if values.empty:
            continue

        axis.hist(
            values,
            bins=80,
            alpha=0.55,
            density=True,
            label=str(channel),
        )
        axis.set_xlabel(interval_column)
        axis.set_ylabel("Densidad")
        axis.grid(True, alpha=0.25)

        if not overlay:
            axis.set_title(str(channel))
        axis.legend(loc="best")

    figure.suptitle(title)
    figure.tight_layout()
    return figure


def plot_series_plotly(
    df: pd.DataFrame,
    title: str,
    style: str,
    show_clean: bool,
    overlay: bool,
):
    import plotly.graph_objects as go
    from plotly.subplots import make_subplots

    channels = (
        df[["channel", "channel_index"]]
        .drop_duplicates()
        .sort_values("channel_index")
    )
    channel_names = channels["channel"].tolist()
    n_channels = len(channel_names)

    rows = 1 if overlay else n_channels
    figure = make_subplots(
        rows=rows,
        cols=1,
        shared_xaxes=not overlay,
        subplot_titles=None if overlay else channel_names,
        vertical_spacing=min(0.04, 0.3 / max(rows, 1)),
    )

    mode_by_style = {
        "points": "markers",
        "line": "lines",
        "line-points": "lines+markers",
    }

    for index, channel in enumerate(channel_names):
        channel_df = df.loc[df["channel"] == channel].sort_values("time")
        row = 1 if overlay else index + 1

        figure.add_trace(
            go.Scattergl(
                x=channel_df["time"],
                y=channel_df["value"],
                mode=mode_by_style[style],
                name=f"{channel} observado",
                marker={"size": 4},
                line={"width": 1},
            ),
            row=row,
            col=1,
        )

        if show_clean and "clean_value" in channel_df.columns:
            figure.add_trace(
                go.Scattergl(
                    x=channel_df["time"],
                    y=channel_df["clean_value"],
                    mode="lines",
                    name=f"{channel} limpio",
                    line={"width": 1.5},
                ),
                row=row,
                col=1,
            )

        figure.update_yaxes(title_text="Valor", row=row, col=1)

    figure.update_xaxes(title_text="Tiempo", row=rows, col=1)
    figure.update_layout(
        title=title,
        height=max(500, 280 * rows),
        hovermode="x unified" if overlay else "closest",
        template="plotly_white",
    )
    return figure


