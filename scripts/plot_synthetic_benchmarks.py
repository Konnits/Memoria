def save_or_show_matplotlib(
    figure,
    output: Path | None,
    dpi: int,
    no_show: bool,
) -> None:
    import matplotlib.pyplot as plt

    if output is not None:
        output = output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        figure.savefig(output, dpi=dpi, bbox_inches="tight")
        print(f"Figure saved to: {output}")

    if not no_show:
        plt.show()
    else:
        plt.close(figure)


def save_or_show_plotly(
    figure,
    output: Path | None,
    no_show: bool,
) -> None:
    if output is not None:
        output = output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)

        if output.suffix.lower() != ".html":
            raise ValueError(
                "Plotly output must use the .html extension unless kaleido "
                "is installed and explicit static-image support is added."
            )

        figure.write_html(
            output,
            include_plotlyjs="cdn",
            full_html=True,
        )
        print(f"Interactive figure saved to: {output}")

    if not no_show:
        figure.show()


def main() -> None:
    args = parse_args()

    if args.start_time is not None and args.end_time is not None:
        if args.start_time > args.end_time:
            raise ValueError("--start-time cannot be greater than --end-time.")

    observations_file = resolve_observations_file(args.input)
    print(f"Reading: {observations_file}")

    observations = read_observations(
        file_path=observations_file,
        split=args.split,
        start_time=args.start_time,
        end_time=args.end_time,
    )

    if observations.empty:
        raise ValueError(
            "No observations remain after applying the requested filters."
        )

    observations = normalize_channel_columns(observations)
    observations = select_channels(
        observations,
        parse_channel_tokens(args.channels),
    )

    original_rows = len(observations)
    observations = downsample_by_channel(
        observations,
        max_points=args.max_points,
    )
    plotted_rows = len(observations)

    title = args.title or infer_title(observations_file, args.plot)
    channels = observations["channel"].nunique()

    print(
        f"Loaded rows after filters: {original_rows:,}\n"
        f"Rows rendered: {plotted_rows:,}\n"
        f"Channels rendered: {channels}"
    )

    if args.backend == "matplotlib":
        if args.plot == "series":
            figure = plot_series_matplotlib(
                df=observations,
                title=title,
                style=args.style,
                show_clean=args.show_clean,
                overlay=args.overlay,
            )
        else:
            figure = plot_intervals_matplotlib(
                df=observations,
                title=title,
                overlay=args.overlay,
            )

        save_or_show_matplotlib(
            figure=figure,
            output=args.output,
            dpi=args.dpi,
            no_show=args.no_show,
        )
        return

    if args.plot == "series":
        figure = plot_series_plotly(
            df=observations,
            title=title,
            style=args.style,
            show_clean=args.show_clean,
            overlay=args.overlay,
        )
    else:
        figure = plot_intervals_plotly(
            df=observations,
            title=title,
            overlay=args.overlay,
        )

    save_or_show_plotly(
        figure=figure,
        output=args.output,
        no_show=args.no_show,
    )


if __name__ == "__main__":
    try:
        main()
    except (FileNotFoundError, ValueError, ImportError) as error:
        print(f"Error: {error}", file=sys.stderr)
        raise SystemExit(1) from error