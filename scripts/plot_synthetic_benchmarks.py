"""Visualize synthetic irregular time-series datasets.

The script supports the folder layout produced by
generate_synthetic_benchmarks.py and can read either Parquet or CSV files.

Examples
--------
Plot a univariate dataset with Matplotlib:

    python scripts/plot_synthetic_benchmarks.py \
        --input data/univariate/hard_mixed/hard_mixed_0000 \
        --backend matplotlib \
        --output outputs/hard_mixed_univariate.png

Plot selected channels from a multivariate dataset with Plotly:

    python scripts/plot_synthetic_benchmarks.py \
        --input data/multivariate/hard_mixed/hard_mixed_0000 \
        --channels x00,x01,x05 \
        --backend plotly \
        --output outputs/hard_mixed_multivariate.html

Plot only test observations in a time range:

    python scripts/plot_synthetic_benchmarks.py \
        --input data/multivariate/informative/informative_0000 \
        --split test \
        --start-time 70 \
        --end-time 100 \
        --max-points 30000
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Iterable, Sequence

import numpy as np
import pandas as pd


DEFAULT_COLUMNS = (
    "dataset_id",
    "channel",
    "channel_index",
    "time",
    "value",
    "clean_value",
    "delta_t",
    "delta_t_channel",
    "delta_t_global",
    "split",
    "event_index",
)


